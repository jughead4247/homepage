// =====================================================
// SHUFFLE ANSWERS
// =====================================================

function shuffleAnswers() {

    questions.forEach(question => {

        for (
            let i = question.answers.length - 1;
            i > 0;
            i--
        ) {

            const j =
                Math.floor(
                    Math.random() * (i + 1)
                );

            [
                question.answers[i],
                question.answers[j]
            ] =
            [
                question.answers[j],
                question.answers[i]
            ];

        }

    });

}


// =====================================================
// START QUIZ
// =====================================================

function startQuiz() {

    shuffleAnswers();

    currentQuestion = 0;

    selectedAnswers =
        new Array(questions.length).fill(null);


    startScreen.classList.add("hidden");

    resultScreen.classList.add("hidden");

    quizScreen.classList.remove("hidden");

    homeInfo.classList.add("hidden");


    if (suggestionsCard) {
        suggestionsCard.classList.add("hidden");
    }


    progressBar.style.width = "0%";

    showQuestion();

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


// =====================================================
// SHOW QUESTION
// =====================================================

function showQuestion() {

    const current =
        questions[currentQuestion];


    questionNumber.textContent =
        `Question ${currentQuestion + 1} of ${questions.length}`;


    questionText.textContent =
        current.question;


    answersContainer.innerHTML = "";


    const progress =
        ((currentQuestion + 1) /
            questions.length) * 100;


    progressBar.style.width =
        `${progress}%`;


    current.answers.forEach(
        (answer, index) => {

            const button =
                document.createElement("button");


            button.className =
                "answer";


            button.type =
                "button";


            button.textContent =
                answer[0];


            if (
                selectedAnswers[currentQuestion] === index
            ) {

                button.classList.add(
                    "selected"
                );

            }


            button.addEventListener(
                "click",
                () => {

                    selectAnswer(index);

                }
            );


            answersContainer.appendChild(
                button
            );

        }
    );


    updateNavigation();

}


// =====================================================
// SELECT ANSWER
// =====================================================

function selectAnswer(answerIndex) {

    selectedAnswers[currentQuestion] =
        answerIndex;


    const buttons =
        answersContainer.querySelectorAll(
            ".answer"
        );


    buttons.forEach(
        (button, index) => {

            button.classList.toggle(
                "selected",
                index === answerIndex
            );

        }
    );


    updateNavigation();


    const questionAtSelection =
        currentQuestion;


    setTimeout(
        () => {

            if (
                currentQuestion ===
                    questionAtSelection &&

                selectedAnswers[
                    questionAtSelection
                ] === answerIndex &&

                currentQuestion <
                    questions.length - 1
            ) {

                currentQuestion++;

                showQuestion();

            }

        },
        180
    );

}


// =====================================================
// NEXT BUTTON
// =====================================================

function goNext() {

    if (
        selectedAnswers[currentQuestion] === null
    ) {

        return;

    }


    if (
        currentQuestion ===
        questions.length - 1
    ) {

        const allAnswered =
            selectedAnswers.every(
                answer => answer !== null
            );


        if (allAnswered) {

            showResult();

        }


        return;

    }


    currentQuestion++;

    showQuestion();

}


// =====================================================
// BACK BUTTON
// =====================================================

function goBack() {

    if (currentQuestion > 0) {

        currentQuestion--;

        showQuestion();

    }

}


// =====================================================
// NAVIGATION
// =====================================================

function updateNavigation() {

    const isFirst =
        currentQuestion === 0;


    const isLast =
        currentQuestion ===
        questions.length - 1;


    const currentAnswered =
        selectedAnswers[
            currentQuestion
        ] !== null;


    const allAnswered =
        selectedAnswers.every(
            answer => answer !== null
        );


    backButton.disabled =
        isFirst;


    if (isLast) {

        nextButton.classList.add("hidden");

        submitButton.classList.remove("hidden");

        submitButton.disabled =
            !allAnswered;


        submitButton.textContent =
            allAnswered
                ? "SUBMIT"
                : "Answer All Questions";

    } else {

        nextButton.classList.remove("hidden");

        submitButton.classList.add("hidden");

        nextButton.textContent =
            "Next →";

        nextButton.disabled =
            !currentAnswered;

    }

}


// =====================================================
// CALCULATE SCORE
// =====================================================

function calculateScore() {

    let correctAnswers = 0;


    selectedAnswers.forEach(
        (answerIndex, questionIndex) => {

            if (answerIndex === null) {
                return;
            }


            correctAnswers +=
                questions[
                    questionIndex
                ].answers[
                    answerIndex
                ][1];

        }
    );


    return correctAnswers;

}


