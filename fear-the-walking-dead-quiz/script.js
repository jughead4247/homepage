/* ===============================
   START QUIZ
   =============================== */

function startQuiz() {

    currentQuestion = 0;

    selectedAnswers =
        new Array(questions.length).fill(null);

    startScreen.classList.add("hidden");

    resultScreen.classList.add("hidden");

    quizScreen.classList.remove("hidden");

    homeInfo.classList.add("hidden");

    if (suggestionsCard) {
        suggestionsCard.classList.add("hidden");
    }

    progressBar.style.width = "0%";

    showQuestion();

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


/* ===============================
   SHOW QUESTION
   =============================== */

function showQuestion() {

    const current =
        questions[currentQuestion];

    questionNumber.textContent =
        `Question ${currentQuestion + 1} of ${questions.length}`;

    questionText.textContent =
        current.question;

    answersContainer.innerHTML = "";

    const progress =
        ((currentQuestion + 1) / questions.length) * 100;

    progressBar.style.width =
        `${progress}%`;


    current.answers.forEach(
        (answer, index) => {

            const button =
                document.createElement("button");

            button.className =
                "answer";

            button.type =
                "button";

            button.textContent =
                answer[0];


            if (
                selectedAnswers[currentQuestion] === index
            ) {

                button.classList.add(
                    "selected"
                );

            }


            button.addEventListener(
                "click",
                function () {

                    selectAnswer(index);

                }
            );


            answersContainer.appendChild(
                button
            );

        }
    );


    updateNavigation();

}


/* ===============================
   SELECT ANSWER
   =============================== */

function selectAnswer(answerIndex) {

    selectedAnswers[currentQuestion] =
        answerIndex;


    const buttons =
        answersContainer.querySelectorAll(
            ".answer"
        );


    buttons.forEach(
        (button, index) => {

            button.classList.toggle(
                "selected",
                index === answerIndex
            );

        }
    );


    updateNavigation();


    /*
       AUTO FORWARD

       Wait 180ms so the selected state
       is visible before moving forward.
    */

    const questionAtSelection =
        currentQuestion;


    setTimeout(
        function () {

            /*
               Make sure the user has not
               moved manually during the delay.
            */

            if (
                currentQuestion === questionAtSelection &&
                selectedAnswers[questionAtSelection] === answerIndex &&
                currentQuestion < questions.length - 1
            ) {

                currentQuestion++;

                showQuestion();

            }

        },
        180
    );

}


/* ===============================
   NEXT / SUBMIT
   =============================== */

function goNext() {

    /*
       Do nothing if current question
       has not been answered.
    */

    if (
        selectedAnswers[currentQuestion] === null
    ) {

        return;

    }


    /*
       LAST QUESTION
    */

    if (
        currentQuestion === questions.length - 1
    ) {

        const allAnswered =
            selectedAnswers.every(
                answer => answer !== null
            );


        if (allAnswered) {

            showResult();

        }

        return;

    }


    /*
       NORMAL NEXT QUESTION
    */

    currentQuestion++;

    showQuestion();

}


/* ===============================
   BACK
   =============================== */

function goBack() {

    if (currentQuestion > 0) {

        currentQuestion--;

        showQuestion();

    }

}


/* ===============================
   NAVIGATION STATE
   =============================== */

function updateNavigation() {

    const isFirst =
        currentQuestion === 0;

    const isLast =
        currentQuestion === questions.length - 1;

    const currentAnswered =
        selectedAnswers[currentQuestion] !== null;

    const allAnswered =
        selectedAnswers.every(
            answer => answer !== null
        );


    /*
       BACK BUTTON
    */

    backButton.disabled =
        isFirst;


    /*
       LAST QUESTION
    */

    if (isLast) {

        nextButton.classList.remove(
            "hidden"
        );

        nextButton.textContent =
            allAnswered
                ? "SUBMIT"
                : "Answer All Questions";

        nextButton.disabled =
            !allAnswered;

        nextButton.classList.toggle(
            "submit-ready",
            allAnswered
        );

        return;

    }


    /*
       NORMAL QUESTION
    */

    nextButton.classList.remove(
        "hidden"
    );

    nextButton.textContent =
        "Next →";

    nextButton.disabled =
        !currentAnswered;

    nextButton.classList.remove(
        "submit-ready"
    );

}


/* ===============================
   CALCULATE RAW SCORE
   =============================== */

function calculateScore() {

    let score = 0;


    selectedAnswers.forEach(
        (answerIndex, questionIndex) => {

            if (answerIndex !== null) {

                score +=
                    questions[questionIndex]
                        .answers[answerIndex][1];

            }

        }
    );


    return score;

}


/* ===============================
   COUNT CORRECT ANSWERS
   =============================== */

function calculateCorrectAnswers() {

    let correct = 0;


    selectedAnswers.forEach(
        (answerIndex, questionIndex) => {

            if (
                answerIndex !== null &&
                questions[questionIndex]
                    .answers[answerIndex][1] === 2
            ) {

                correct++;

            }

        }
    );


    return correct;

}


/* ===============================
   SHOW RESULT
   =============================== */

function showResult() {

    const totalQuestions =
        questions.length;


    const correctAnswers =
        calculateCorrectAnswers();


    const incorrectAnswers =
        totalQuestions - correctAnswers;


    /*
       Each correct answer = 2 points.

       50 questions × 2 = 100 maximum.
    */

    const rawScore =
        calculateScore();


    const score =
        Math.round(
            (rawScore / (totalQuestions * 2)) * 100
        );


    const accuracy =
        score;


    quizScreen.classList.add(
        "hidden"
    );

    resultScreen.classList.remove(
        "hidden"
    );

    homeInfo.classList.remove(
        "hidden"
    );


    if (suggestionsCard) {

        suggestionsCard.classList.remove(
            "hidden"
        );

    }


    /* ===============================
       MAIN SCORE
       =============================== */

    const finalScore =
        document.getElementById(
            "final-score"
        );


    if (finalScore) {

        finalScore.textContent =
            `${score}%`;

    }


    /* ===============================
       RESULT BREAKDOWN
       =============================== */

    const correctCount =
        document.getElementById(
            "correct-count"
        );

    const incorrectCount =
        document.getElementById(
            "incorrect-count"
        );

    const totalCount =
        document.getElementById(
            "total-count"
        );

    const accuracyPercent =
        document.getElementById(
            "accuracy-percent"
        );


    if (correctCount) {

        correctCount.textContent =
            correctAnswers;

    }


    if (incorrectCount) {

        incorrectCount.textContent =
            incorrectAnswers;

    }


    if (totalCount) {

        totalCount.textContent =
            totalQuestions;

    }


    if (accuracyPercent) {

        accuracyPercent.textContent =
            `${accuracy}%`;

    }


    /* ===============================
       FTWD RESULT LEVELS
       =============================== */

    let title;
    let description;
    let knowledge;


    if (score <= 20) {

        title =
            "🧟 Walker Fodder";

        description =
            "The walkers may have you surrounded. You remember a few details of Fear the Walking Dead, but there is plenty more of the apocalypse to revisit.";

        knowledge =
            "Casual Viewer";


    } else if (score <= 40) {

        title =
            "🏚️ Survivor";

        description =
            "You have survived some of the major events, but several characters, communities and turning points from Fear the Walking Dead slipped through the cracks.";

        knowledge =
            "Casual Fan";


    } else if (score <= 60) {

        title =
            "🔪 Apocalypse Survivor";

        description =
            "Not bad! You remember many of the important characters, conflicts and major events across Fear the Walking Dead.";

        knowledge =
            "Good Fan";


    } else if (score <= 80) {

        title =
            "⚔️ Seasoned Survivor";

        description =
            "Impressive! You have a strong memory of the survivors, factions, major communities and turning points throughout the series.";

        knowledge =
            "Dedicated Fan";


    } else if (score <= 94) {

        title =
            "🧠 Fear Expert";

        description =
            "Excellent! You remember most of the important characters, events, locations, crossovers and major developments from Fear the Walking Dead.";

        knowledge =
            "Expert Fan";


    } else {

        title =
            "🔥 Fear Encyclopedia";

        description =
            "Outstanding! You remembered an enormous amount of detail from Fear the Walking Dead across all eight seasons.";

        knowledge =
            "Ultimate Fan";

    }


    const resultTitle =
        document.getElementById(
            "result-title"
        );

    const resultDescription =
        document.getElementById(
            "result-description"
        );

    const knowledgeLevel =
        document.getElementById(
            "knowledge-level"
        );


    if (resultTitle) {

        resultTitle.textContent =
            title;

    }


    if (resultDescription) {

        resultDescription.textContent =
            description;

    }


    if (knowledgeLevel) {

        knowledgeLevel.textContent =
            knowledge;

    }


    progressBar.style.width =
        "100%";


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


